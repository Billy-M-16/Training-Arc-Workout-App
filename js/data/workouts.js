// Built-in workout library.
// Block types:
//  sets   {t, sets, rest, ex:['id:reps', ...]}         superset: do the list, tap, rest, repeat
//  int    {t, work, rest, rounds, rrest?, ex:['id']}   timed intervals, each round cycles every exercise
//  emom   {t, min, ex:['id:reps']}                     each minute rotates to the next station ('n' = minute number)
//  amrap  {t, min, ex:['id:reps']}                     as many rounds as possible, tap each round
//  ladder {t, reps:[10,9,...], cap?, ex:['id*mult']}   every round uses the rep count (x mult), tap each round
//  rounds {t, rounds, rest?, cap?, ex:['id:reps']}     fixed rounds, tap each round
//  chip   {t, cap?, ex:['id:reps']}                    work down the list once, tap each exercise
//  flow   {t, rounds?, ex:['id:seconds']}              timed holds back to back (mobility)
//  timed  {t, ex:'id', sec}                            one long timed effort
// Workout `min` = total time. 25 min and up includes warm-up and cool-down;
// shorter sessions have a short warm-up added on top.

